NUM_WALLET_TRANSACTIONS = 100_000
NUM_ACTIVE_TRIPS = 30
NUM_IN_TRANSIT = 10
BATCH_SIZE = 5_000


# ============================================================
# CONNECTION
# ============================================================

def get_connection():
    if psycopg2 is None:
        sys.exit("psycopg2 is not installed: python3 -m pip install psycopg2-binary")
    cfg = pg_config()
    if not cfg["password"] and sys.stdin.isatty():
        import getpass
        cfg["password"] = getpass.getpass("PostgreSQL password (empty for none): ") or None
    if not cfg["password"]:
        cfg.pop("password")
    conn = psycopg2.connect(**cfg)
    register_uuid(conn_or_curs=conn)
    return conn


# ============================================================
# 1. CLEAR
# ============================================================

def clear_existing_data(conn):
    # TRUNCATE does not fire the row-level "append-only" trigger on
    # wallet_audit_logs, so resetting the database stays possible.
    with conn.cursor() as cur:
        cur.execute(
            "TRUNCATE trips, wallet_audit_logs, riders, vehicles RESTART IDENTITY CASCADE;"
        )
    conn.commit()
    print("Existing RideSync data cleared.")


# ============================================================
# 2. RIDERS
# ============================================================

def insert_riders(conn):
    rows = []
    out = []
    for r in riders():
        balance = Decimal(random.randint(8000, 12000))
        rows.append((r["id"], r["name"], balance))
        out.append({"id": r["id"], "name": r["name"], "balance": balance})

    with conn.cursor() as cur:
        execute_values(cur, "INSERT INTO riders (id, name, wallet_balance) VALUES %s", rows)
    conn.commit()
    print(f"Inserted {len(out):,} riders.")
    return out


# ============================================================
# 3. VEHICLES
# ============================================================

def insert_vehicles(conn):
    fleet = vehicle_fleet()
    rows = [(v["id"], v["license_plate"], v["class"], v["is_active"]) for v in fleet]
    with conn.cursor() as cur:
        execute_values(
            cur,
            "INSERT INTO vehicles (id, license_plate, class, is_active) VALUES %s",
            rows,
        )
    conn.commit()
    inactive = sum(1 for v in fleet if not v["is_active"])
    print(f"Inserted {len(fleet):,} vehicles ({inactive} inactive).")
    return fleet


# ============================================================
# 4. COMPLETED TRIPS (history)
# ============================================================

def random_trip_time(now):
    """Random time between 07:00 and 22:00 UTC on one of the last HISTORY_DAYS days."""
    day = (now - timedelta(days=random.randint(0, HISTORY_DAYS - 1))).replace(
        hour=0, minute=0, second=0, microsecond=0
    )
    ts = day + timedelta(seconds=random.randint(7 * 3600, 22 * 3600))
    if ts > now - timedelta(minutes=5):  # never in the future
        ts -= timedelta(days=1)
    return ts


def insert_completed_trips(conn, rider_list, fleet):
    print(f"Generating {NUM_TRIPS:,} completed trips over {HISTORY_DAYS} days...")
    now = datetime.now(timezone.utc)
    sql = """
        INSERT INTO trips (rider_id, vehicle_id, fare_amount, status, created_at)
        VALUES %s
    """
    batch, inserted = [], 0
    with conn.cursor() as cur:
        for _ in range(NUM_TRIPS):
            batch.append((
                random.choice(rider_list)["id"],
                random.choice(fleet)["id"],   # history may include now-retired vehicles
                Decimal(random.randint(100, 800)).quantize(Decimal("0.01")),
                "COMPLETED",
                random_trip_time(now),
            ))
            if len(batch) >= BATCH_SIZE:
                execute_values(cur, sql, batch)
                inserted += len(batch)
                batch.clear()
                conn.commit()
                print(f"  {inserted:,} / {NUM_TRIPS:,}")
        if batch:
            execute_values(cur, sql, batch)
            inserted += len(batch)
            conn.commit()
    print(f"Inserted {inserted:,} completed trips.")


# ============================================================
# 5. WALLET ACTIVITY -> AUDIT LOG (via trigger)
# ============================================================

def create_wallet_activity(conn, rider_list):
    """
    100,000 wallet changes applied with UPDATE riders, so every audit row
    is written by trg_wallet_audit (as in A1).

    A2: operations are applied in chronological order of planned
    timestamps spread over HISTORY_DAYS. After that, the audit timestamps
    (which the trigger stamps with clock_timestamp()) are back-filled to
    the planned historical times, in the same order. Without this, all
    100k rows land in the same few seconds, and the Audit Trail date filter
    has nothing to show. The append-only guard is disabled only for this
    back-fill, inside the same transaction.
    """
    print(f"Generating {NUM_WALLET_TRANSACTIONS:,} wallet transactions...")
    now = datetime.now(timezone.utc)
    start = now - timedelta(days=HISTORY_DAYS)
    span = (now - timedelta(hours=1) - start).total_seconds()
    planned_times = sorted(
        start + timedelta(seconds=random.uniform(0, span))
        for _ in range(NUM_WALLET_TRANSACTIONS)
    )

    balances = {r["id"]: r["balance"] for r in rider_list}
    operations = []
    topups = deductions = 0

    for _ in range(NUM_WALLET_TRANSACTIONS):
        rid = random.choice(rider_list)["id"]
        current = balances[rid]
        max_deduction = min(1000, int(current))
        if random.random() < 0.55 or max_deduction < 100:
            amount = Decimal(random.randint(100, 1500))
            topups += 1
        else:
            amount = -Decimal(random.randint(100, max_deduction))
            deductions += 1
        balances[rid] += amount
        operations.append((amount, rid))

    print(f"  top-ups: {topups:,}   deductions: {deductions:,}")
    print("Applying through riders.wallet_balance (trigger writes audit rows)...")

    with conn.cursor() as cur:
        for i in range(0, len(operations), BATCH_SIZE):
            execute_batch(
                cur,
                "UPDATE riders SET wallet_balance = wallet_balance + %s WHERE id = %s",
                operations[i:i + BATCH_SIZE],
                page_size=BATCH_SIZE,
            )
            conn.commit()
            print(f"  {min(i + BATCH_SIZE, len(operations)):,} / {len(operations):,}")

        # ---- back-fill historical timestamps (one transaction) ----
        cur.execute("SELECT count(*) FROM wallet_audit_logs")
        n_rows = cur.fetchone()[0]
        if n_rows != len(operations):
            raise RuntimeError(f"expected {len(operations)} audit rows, found {n_rows}")

        cur.execute("CREATE TEMP TABLE seed_audit_times (seq INT PRIMARY KEY, ts TIMESTAMPTZ) ON COMMIT DROP")
        execute_values(
            cur,
            "INSERT INTO seed_audit_times (seq, ts) VALUES %s",
            [(i + 1, t) for i, t in enumerate(planned_times)],
            page_size=10_000,
        )
        cur.execute("ALTER TABLE wallet_audit_logs DISABLE TRIGGER trg_wallet_audit_immutable")
        cur.execute("""
            UPDATE wallet_audit_logs w
            SET timestamp = s.ts
            FROM (
                SELECT id, row_number() OVER (ORDER BY timestamp, id) AS seq
                FROM wallet_audit_logs
            ) r
            JOIN seed_audit_times s ON s.seq = r.seq
            WHERE w.id = r.id
        """)
        cur.execute("ALTER TABLE wallet_audit_logs ENABLE TRIGGER trg_wallet_audit_immutable")
    conn.commit()
    print("Audit history spread over the last "
          f"{HISTORY_DAYS} days (rows written by trg_wallet_audit).")


# ============================================================
# 6. ACTIVE TRIPS (through the stored procedure)
# ============================================================

def create_active_trips(conn, rider_list, fleet):
    active_vehicles = [v for v in fleet if v["is_active"]]
    trip_ids = []
    with conn.cursor() as cur:
        # only riders who can afford a ride (wallet activity may drain some)
        cur.execute("SELECT id FROM riders WHERE wallet_balance >= 1000 ORDER BY name")
        affordable = [row[0] for row in cur.fetchall()]
        chosen_riders = random.sample(affordable, NUM_ACTIVE_TRIPS)
        chosen_vehicles = random.sample(active_vehicles, NUM_ACTIVE_TRIPS)
        for rid, v in zip(chosen_riders, chosen_vehicles):
            fare = Decimal(random.randint(150, 600))
            cur.execute("CALL sp_book_ride(%s, %s, %s, NULL)", (rid, v["id"], fare))
            trip_ids.append(cur.fetchone()[0])
        for t in trip_ids[:NUM_IN_TRANSIT]:
            cur.execute("CALL sp_update_trip_status(%s, 'IN TRANSIT')", (t,))
    conn.commit()
    print(f"Booked {len(trip_ids)} active trips via sp_book_ride "
          f"({NUM_IN_TRANSIT} moved to IN TRANSIT).")


# ============================================================
# 7. MATERIALIZED VIEW + STATISTICS
# ============================================================

def refresh_and_analyze(conn):
    with conn.cursor() as cur:
        cur.execute("SELECT * FROM refresh_mv_vehicle_stats()")
        refreshed_at, ms = cur.fetchone()
    conn.commit()
    print(f"mv_vehicle_stats refreshed CONCURRENTLY at {refreshed_at} ({ms} ms).")

    # VACUUM must run outside a transaction; it also sets the visibility
    # map so Workflow 2 can use an index-only scan.
    conn.autocommit = True
    with conn.cursor() as cur:
        cur.execute("VACUUM ANALYZE")
    conn.autocommit = False
    print("VACUUM ANALYZE done.")


# ============================================================
# 8. VERIFY
# ============================================================

def verify_data(conn):
    queries = {
        "Riders": "SELECT count(*) FROM riders",
        "Vehicles": "SELECT count(*) FROM vehicles",
        "Trips (total)": "SELECT count(*) FROM trips",
        "Trips (active)": "SELECT count(*) FROM trips WHERE status IN ('REQUESTED','IN TRANSIT')",
        "Wallet audit logs": "SELECT count(*) FROM wallet_audit_logs",
        "Audit days covered": "SELECT count(DISTINCT timestamp::date) FROM wallet_audit_logs",
        "mv_vehicle_stats rows": "SELECT count(*) FROM mv_vehicle_stats",
    }
    print("\n========================================")
    print("        RIDESYNC DATABASE STATUS")
    print("========================================")
    with conn.cursor() as cur:
        results = {}
        for label, q in queries.items():
            cur.execute(q)
            results[label] = cur.fetchone()[0]
            print(f"{label:<24}{results[label]:>10,}")
    print("========================================")
    ok = results["Wallet audit logs"] >= 100_000 and results["Trips (total)"] >= 50_000
    print("SUCCESS: volume requirements met." if ok else "WARNING: volume requirement not met.")


def main():
    random.seed(int(os.getenv("SEED", "42")))
    print("Connecting to RideSync PostgreSQL database...")
    conn = None
    try:
        conn = get_connection()
        print("Connected.\n")
        clear_existing_data(conn)
        rider_list = insert_riders(conn)
        fleet = insert_vehicles(conn)
        insert_completed_trips(conn, rider_list, fleet)
        create_wallet_activity(conn, rider_list)
        create_active_trips(conn, rider_list, fleet)
        refresh_and_analyze(conn)
        verify_data(conn)
        print("\nSeeding completed successfully!")
    except Exception as e:
        if conn and not conn.autocommit:
            conn.rollback()
        print("\nERROR:", e)
        sys.exit(1)
    finally:
        if conn:
            conn.close()


if __name__ == "__main__":
    main()
