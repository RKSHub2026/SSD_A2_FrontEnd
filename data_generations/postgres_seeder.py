"""
RideSync - PostgreSQL seeder

Generates:
  * 1,000 riders, 100 vehicles (5 inactive). Same deterministic fleet as MongoDB (see SHARED FLEET DEFINITION below).
  * 100,000 COMPLETED trips spread over the last 30 days
  * 100,000 wallet transactions. Each one is a real UPDATE on riders.wallet_balance,
    so trg_wallet_audit writes the 100,000 wallet_audit_logs rows.
  * 30 ACTIVE trips (20 REQUESTED + 10 IN TRANSIT), booked through sp_book_ride
  * a refreshed mv_vehicle_stats

A2 changes vs the A1 seeder are listed in the README. Main ones:
  shared fleet ids, audit history spread over 30 days (A1 stamped all
  100k rows with the same seeding second), active trips, MV refresh,
  connection from environment variables, reproducible random seed.

Run (after the sql/ scripts):
    PGPASSWORD=... python3 data_generations/postgres_seeder.py
Environment: PGHOST PGPORT PGDATABASE(ridesync_v2) PGUSER PGPASSWORD SEED
"""

import os
import random
import sys
import uuid
from datetime import datetime, timedelta, timezone
from decimal import Decimal

try:
    import psycopg2
    from psycopg2.extras import execute_batch, execute_values, register_uuid
except ImportError:  # lets the Mongo scripts import the fleet definition without psycopg2
    psycopg2 = None

# ============================================================
# SHARED FLEET DEFINITION  (A2)
# ------------------------------------------------------------
# PostgreSQL and MongoDB must describe the SAME vehicles. In A1 they did not
# (Postgres: random uuid4 ids + MH..AB.... plates; Mongo: V00001..V00150 +
# NYC-### plates), so no ping or review could be joined to a bookable vehicle.
#
# Ids are uuid5 values from a fixed namespace: identical in both databases and
# on every re-seed, with no cross-database connection needed while seeding.
# The other scripts in this folder import these helpers from here:
#     from postgres_seeder import vehicle_fleet, riders, ...
# ============================================================

# Fixed namespace -> deterministic ids (never change this once data exists)
NAMESPACE = uuid.UUID("3f9a1c52-7b1e-4d2a-9c3e-5a6b7c8d9e01")

NUM_RIDERS = 1000
NUM_VEHICLES = 100

VEHICLE_CLASSES = ["Sedan", "SUV", "Hatchback"]

# Every 20th vehicle is inactive (out of service) so the UI can
# demonstrate the "vehicle is not active" failure (RS003).
INACTIVE_EVERY = 20

# Telemetry is generated in Mumbai, matching the MH (Maharashtra) plates.
# (A1 used Manhattan; moved for A2 so the map, the plates and the pickup
# points in shared/constants.js describe the same city.)
# GeoJSON order: [longitude, latitude]
CITY_CENTER = (72.8426, 19.0178)   # Dadar station
CITY_SPREAD_LON = 0.04             # kept for older scripts; LAND_ZONES is used
CITY_SPREAD_LAT = 0.11

# Mumbai is a narrow north-south peninsula, so a plain rectangle would put
# cars in the sea. Each strip is (lat_min, lat_max, lon_min, lon_max),
# south to north: Colaba/Fort, Marine Lines-Lower Parel, Dadar-Sion,
# Bandra-BKC-Kurla, Santacruz-Juhu-Airport-Andheri.
LAND_ZONES = [
    (18.905, 18.960, 72.815, 72.845),
    (18.960, 19.010, 72.810, 72.850),
    (19.010, 19.050, 72.818, 72.865),
    (19.050, 19.080, 72.828, 72.890),
    (19.080, 19.125, 72.826, 72.880),
]
CITY_LAT_MIN = LAND_ZONES[0][0]
CITY_LAT_MAX = LAND_ZONES[-1][1]


def random_city_point(rnd=random):
    """A random [lon, lat] on land, zones weighted by their area."""
    weights = [(z[1] - z[0]) * (z[3] - z[2]) for z in LAND_ZONES]
    lat_min, lat_max, lon_min, lon_max = rnd.choices(LAND_ZONES, weights=weights)[0]
    return rnd.uniform(lon_min, lon_max), rnd.uniform(lat_min, lat_max)


def keep_in_city(lon, lat):
    """Clamps a point onto the land strips (used by the random walk)."""
    lat = min(max(lat, CITY_LAT_MIN), CITY_LAT_MAX)
    for lat_min, lat_max, lon_min, lon_max in LAND_ZONES:
        if lat_min <= lat <= lat_max:
            return min(max(lon, lon_min), lon_max), lat
    return lon, lat


def in_city(lon, lat):
    """True when a point lies on one of the land strips."""
    return any(a <= lat <= b and c <= lon <= d for a, b, c, d in LAND_ZONES)


# Days of trip / wallet history generated by the seeder
HISTORY_DAYS = 30


def rider_id(i: int) -> uuid.UUID:
    return uuid.uuid5(NAMESPACE, f"rider-{i}")


def rider_name(i: int) -> str:
    return f"Rider_{i:04d}"


def riders():
    """[{id, name}] for i = 1..NUM_RIDERS."""
    return [{"id": rider_id(i), "name": rider_name(i)} for i in range(1, NUM_RIDERS + 1)]


def vehicle_fleet():
    """Deterministic fleet shared by PostgreSQL and MongoDB."""
    fleet = []
    for i in range(1, NUM_VEHICLES + 1):
        rnd = random.Random(i)  # deterministic per vehicle
        fleet.append({
            "id": uuid.uuid5(NAMESPACE, f"vehicle-{i}"),
            "index": i,
            "license_plate": f"MH{(i - 1) % 99 + 1:02d}AB{i:04d}",  # A1 format kept
            "class": rnd.choice(VEHICLE_CLASSES),
            "is_active": i % INACTIVE_EVERY != 0,
        })
    return fleet


